import { BOARD_TOOLS } from "@/lib/board-tool-defs";
import { BOARD_ID, boardStore } from "@/lib/boards";
import { runBoardTool } from "@/lib/board-tools";
import { StorageNotConfiguredError } from "@/lib/db";
import { demoBoardItems, listDemoBoards } from "@/lib/demo-boards";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

/**
 * The whiteboard as an MCP server (Streamable HTTP, JSON responses, no sessions). Point an MCP client
 * (Claude Code, Claude Desktop) at <site>/api/mcp. Every board tool takes a board_id: the 12 characters
 * after /b/ in the board's address.
 */

const PROTOCOL_VERSIONS = ["2025-06-18", "2025-03-26", "2024-11-05"];

const boardId = { type: "string", description: "The board's id: the 12 characters after /b/ in its address." };

const TOOLS = [
  {
    name: "create_board",
    description: "Start a new whiteboard, empty or as a copy of a demo board. Returns its id and address.",
    inputSchema: {
      type: "object",
      properties: {
        title: { type: "string" },
        demo: { type: "string", description: "A demo board's slug, from list_demo_boards." },
      },
      additionalProperties: false,
    },
  },
  {
    name: "list_demo_boards",
    description: "The ready-made demo boards a new board can copy.",
    inputSchema: { type: "object", properties: {}, additionalProperties: false },
  },
  ...BOARD_TOOLS.map((t) => ({
    name: t.name,
    description: t.description,
    inputSchema: {
      ...t.input_schema,
      properties: { board_id: boardId, ...t.input_schema.properties },
      required: ["board_id", ...t.input_schema.required],
    },
  })),
];

interface RpcRequest {
  jsonrpc?: string;
  id?: string | number | null;
  method?: string;
  params?: Record<string, unknown>;
}

const result = (id: RpcRequest["id"], value: unknown) => ({ jsonrpc: "2.0", id: id ?? null, result: value });
const rpcError = (id: RpcRequest["id"], code: number, message: string) => ({ jsonrpc: "2.0", id: id ?? null, error: { code, message } });
const text = (t: string, isError = false) => ({ content: [{ type: "text", text: t }], isError });

async function callTool(name: string, args: Record<string, unknown>, origin: string) {
  if (name === "list_demo_boards") {
    const demos = await listDemoBoards();
    return text(demos.map((d) => `- ${d.slug}: ${d.title} (${JSON.stringify(d.prompt)})`).join("\n") || "No demo boards.");
  }
  if (name === "create_board") {
    let init = {};
    if (typeof args.demo === "string") {
      const demo = await demoBoardItems(args.demo);
      if (!demo) return text(`There is no demo board ${JSON.stringify(args.demo)}.`, true);
      init = demo;
    } else if (typeof args.title === "string") init = { title: args.title };
    const board = await boardStore().createBoard(init);
    return text(`Created board ${board.id} (${JSON.stringify(board.title)}): ${origin}/b/${board.id}`);
  }
  if (!BOARD_TOOLS.some((t) => t.name === name)) return null;
  const id = args.board_id;
  if (typeof id !== "string" || !BOARD_ID.test(id)) return text("board_id must be a board's 12-character id.", true);
  const { board_id: _omit, ...input } = args;
  void _omit;
  const r = await runBoardTool(id, name, input);
  return text(r.text, r.isError);
}

async function handle(req: RpcRequest, origin: string): Promise<object | null> {
  const id = req.id;
  const isNotification = id === undefined;
  switch (req.method) {
    case "initialize": {
      const asked = typeof req.params?.protocolVersion === "string" ? req.params.protocolVersion : "";
      return result(id, {
        protocolVersion: PROTOCOL_VERSIONS.includes(asked) ? asked : PROTOCOL_VERSIONS[0],
        capabilities: { tools: { listChanged: false } },
        serverInfo: { name: "livesim-whiteboard", version: "0.1.0" },
        instructions:
          "Read and change Live Sim whiteboards. A board's id is in its address (/b/<id>). Start with get_board and get_changelog. Simulation boxes are generated by the browser that has the board open.",
      });
    }
    case "ping":
      return result(id, {});
    case "tools/list":
      return result(id, { tools: TOOLS });
    case "tools/call": {
      const name = typeof req.params?.name === "string" ? req.params.name : "";
      const args = (req.params?.arguments ?? {}) as Record<string, unknown>;
      try {
        const out = await callTool(name, args, origin);
        return out ? result(id, out) : rpcError(id, -32602, `Unknown tool ${name}.`);
      } catch (err) {
        const message = err instanceof StorageNotConfiguredError ? err.message : "The tool failed on the server.";
        if (!(err instanceof StorageNotConfiguredError)) console.error("[mcp]", err);
        return result(id, text(message, true));
      }
    }
    default:
      if (isNotification) return null;
      return rpcError(id, -32601, `Method not found: ${req.method}`);
  }
}

export async function POST(req: Request) {
  let body: unknown;
  try {
    body = await req.json();
  } catch {
    return Response.json(rpcError(null, -32700, "Parse error"), { status: 400 });
  }
  const origin = new URL(req.url).origin;
  const batch = Array.isArray(body) ? (body as RpcRequest[]) : [body as RpcRequest];
  const replies = (await Promise.all(batch.map((r) => handle(r ?? {}, origin)))).filter((r): r is object => r !== null);
  // Only notifications: nothing to answer.
  if (!replies.length) return new Response(null, { status: 202 });
  return Response.json(Array.isArray(body) ? replies : replies[0]);
}

/** No server-to-client stream: this server only answers requests. */
export function GET() {
  return new Response("Method Not Allowed", { status: 405, headers: { Allow: "POST" } });
}
